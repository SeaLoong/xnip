class CommandContracts(unittest.TestCase):
    def test_plan_emits_small_json_and_appends_github_outputs(self):
        with repository() as repo:
            before = repo.commit("base")
            repo.write("src/main.rs")
            head = repo.commit("runtime")
            output = repo.path / "outputs"
            output.write_text("previous=value\n", encoding="utf-8")
            result = subprocess.run(
                [sys.executable, str(HELPER), "plan", "--root", str(repo.path),
                 "--before", before, "--head", head, "--run-number", "42", "--output", str(output)],
                capture_output=True, check=True,
            )
            parsed = json.loads(result.stdout)
            self.assertTrue(parsed["publish"])
            self.assertEqual(
                output.read_text(encoding="utf-8"),
                f"previous=value\npublish=true\nversion={parsed['version']}\ntag={parsed['tag']}\nprerelease=true\n",
            )

    def test_github_output_environment_path_and_validation_failure(self):
        with repository() as repo:
            output = repo.path / "outputs"
            command = [sys.executable, str(HELPER), "version", "--root", str(repo.path), "--github-output"]
            result = subprocess.run(command, capture_output=True, env={**os.environ, "GITHUB_OUTPUT": str(output)})
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(output.read_text(encoding="utf-8"), "version=0.2.0\ntag=v0.2.0\nprerelease=false\n")
            failed = subprocess.run(command + ["--tag", "v9.0.0"], capture_output=True, env={**os.environ, "GITHUB_OUTPUT": str(output)})
            self.assertNotEqual(failed.returncode, 0)
            self.assertEqual(failed.stdout, b"")
            self.assertEqual(output.read_text(encoding="utf-8"), "version=0.2.0\ntag=v0.2.0\nprerelease=false\n")

    def test_missing_github_output_fails_with_a_clear_error(self):
        with repository() as repo:
            env = dict(os.environ)
            env.pop("GITHUB_OUTPUT", None)
            result = subprocess.run(
                [sys.executable, str(HELPER), "version", "--root", str(repo.path), "--github-output"],
                capture_output=True, env=env,
            )
            self.assertNotEqual(result.returncode, 0)
            self.assertIn(b"GITHUB_OUTPUT", result.stderr)


