"""Offline contracts for release eligibility, versions and isolated build stamping."""

from __future__ import annotations

from contextlib import contextmanager
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
HELPER = ROOT / ".github" / "scripts" / "release.py"
SPEC = importlib.util.spec_from_file_location("xnip_release", HELPER)
assert SPEC is not None and SPEC.loader is not None
release = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(release)

MANIFEST = b'''[workspace]
members = [".", "xtask"]

[package]
name = "xnip"
version = "0.2.0" # runtime version

[dependencies]
semver = "1"
some_crate = { version = "0.2.0" }
'''
LOCK = b'''# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "some_crate"
version = "0.2.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"

[[package]]
name = "xnip"
version = "0.2.0"
dependencies = [
 "some_crate",
]

[[package]]
name = "xtask"
version = "0.0.0"
'''


class Repository:
    def __init__(self, path: Path):
        self.path = path
        self.git("init", "--quiet", "--initial-branch=main")
        self.git("config", "user.name", "Release contract")
        self.git("config", "user.email", "release-contract@example.invalid")
        self.git("config", "core.autocrlf", "false")
        self.write("Cargo.toml", MANIFEST)
        self.write("Cargo.lock", LOCK)

    def git(self, *args: str) -> str:
        result = subprocess.run(
            ["git", "-C", str(self.path), *args], capture_output=True, check=True,
            env={**os.environ, "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull},
        )
        return result.stdout.decode("utf-8").strip()

    def write(self, path: str, value: bytes = b"fixture\n") -> None:
        destination = self.path / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(value)

    def commit(self, message: str) -> str:
        self.git("add", "--all")
        self.git("commit", "--quiet", "-m", message)
        return self.git("rev-parse", "HEAD")

    def plan(self, before: str, head: str, run_number: int = 42) -> dict:
        return release.plan(self.path, before, head, run_number)


@contextmanager
def repository():
    with tempfile.TemporaryDirectory(prefix="xnip-release-contract-") as folder:
        yield Repository(Path(folder))


